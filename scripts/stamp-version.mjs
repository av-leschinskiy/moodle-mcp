#!/usr/bin/env node
// Generates src/version.ts with build metadata (semver, git SHA, build date).
// Idempotent: skips write if content unchanged (avoids triggering rebuilds/hooks).

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

const pkg = JSON.parse(readFileSync(resolve(repoRoot, 'package.json'), 'utf8'));

function git(args) {
  try {
    return execSync(`git ${args}`, { cwd: repoRoot, encoding: 'utf8' }).trim();
  } catch {
    return null;
  }
}

// ВАЖНО про смысл этого SHA. Стэмпер работает из pre-commit, то есть ДО
// создания коммита, поэтому `rev-parse HEAD` — это коммит-РОДИТЕЛЬ, а не тот,
// в который попадёт сборка. Иначе и быть не может: SHA коммита есть хэш его
// содержимого, и записать его внутрь этого же содержимого невозможно.
// Поэтому поле называется BASE_COMMIT — «на чём основана сборка», а точная
// идентификация выпуска идёт по VERSION (её бампает bump-patch.mjs).
const baseCommit = git('rev-parse HEAD') ?? 'unknown';
const baseCommitShort = git('rev-parse --short HEAD') ?? 'unknown';

// Суффикс `-dirty` = «сборка могла разойтись с коммитом».
//
// Считаем по НЕзастейженным правкам и неотслеживаемым файлам в источниках
// (src/, scripts/, package.json): и то и другое означает, что dist собран не из
// того, что уедет в коммит. Два исключения важны:
//
//   • `src/version.ts` — его пишет этот же скрипт, поэтому без исключения он
//     пачкает сам себя: `npm run build` вне коммита оставляет файл изменённым,
//     и следующая сборка получает `-dirty` без единой правки от человека;
//   • `dist/` — артефакт, его пересборка ничего не говорит об исходниках.
//
// Раньше здесь стоял `git status --porcelain`, который в pre-commit видит
// собственный индекс коммита и потому помечал `-dirty` ВСЕГДА: признак, который
// всегда включён, не несёт информации и мешает по багрепорту понять, правил ли
// пользователь код у себя.
const IGNORED_PATHS = new Set(['src/version.ts']);
const SOURCE_PATHS = ['src', 'scripts', 'package.json'];

function changedPaths(command) {
  return (git(`${command} -- ${SOURCE_PATHS.join(' ')}`) ?? '')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !IGNORED_PATHS.has(line));
}

const dirtyPaths = [
  ...changedPaths('diff --name-only'),
  ...changedPaths('ls-files --others --exclude-standard'),
];
const dirty = dirtyPaths.length > 0 ? '-dirty' : '';
const buildDate = new Date().toISOString().slice(0, 10);

const out = `/**
 * AUTO-GENERATED by scripts/stamp-version.mjs — DO NOT EDIT.
 * Regenerated on every \`npm run build\` via the prebuild hook.
 *
 * BASE_COMMIT — коммит, НА КОТОРОМ основана сборка (родитель того коммита,
 * куда она попала): стэмп делается в pre-commit, до появления собственного SHA.
 * Точная идентификация выпуска — VERSION. Суффикс \`-dirty\` означает, что при
 * сборке были незакоммиченные правки, то есть dist мог разойтись с коммитом.
 */
export const VERSION = ${JSON.stringify(pkg.version)};
export const BASE_COMMIT = ${JSON.stringify(baseCommit + dirty)};
export const BASE_COMMIT_SHORT = ${JSON.stringify(baseCommitShort + dirty)};
export const BUILD_DATE = ${JSON.stringify(buildDate)};
export const PACKAGE_NAME = ${JSON.stringify(pkg.name)};
`;

const target = resolve(repoRoot, 'src/version.ts');
const current = existsSync(target) ? readFileSync(target, 'utf8') : '';

// Сравниваем без учёта BUILD_DATE — иначе каждый день файл будет «меняться»,
// и pre-commit hook будет добавлять его в каждый коммит без причины.
const stripDate = (s) => s.replace(/export const BUILD_DATE = .*?;/, '');
if (stripDate(current) === stripDate(out)) {
  process.exit(0);
}

writeFileSync(target, out);
console.error(
  `stamp-version: wrote src/version.ts (v${pkg.version}, base ${baseCommitShort}${dirty}, ${buildDate})`,
);
